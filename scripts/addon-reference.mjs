const hidden = /(?:_CHANNELS?|^NativeAppearance$|^themePreferences$)/
const escapeHtml = (text) =>
  text
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('|', '&#124;')
const ticks = String.fromCharCode(96).repeat(3)
const fence = (text) => [`${ticks}typescript`, text, ticks].join('\n')
const anchor = (text) =>
  text
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .trim()
    .replace(/\s+/g, '-')

function comment(node) {
  const text = (node.leadingComments ?? [])
    .filter(
      (item) => item.type === 'CommentBlock' && item.value.startsWith('*'),
    )
    .map((item) => item.value.replace(/^\s*\* ?/gm, '').trim())
    .join('\n\n')
  const [description, ...tags] = text.split(/(?:^|\n)\s*@/)
  return {
    description: description.trim(),
    parameters: new Map(
      tags
        .filter((tag) => tag.startsWith('param '))
        .map((tag) => {
          const [, name, description] =
            tag.match(/^param\s+(\S+)\s+(?:-\s*)?([\s\S]*)$/) ?? []
          return [name, description?.trim() ?? '']
        }),
    ),
    returns: tags
      .find((tag) => /^returns?\s/.test(tag))
      ?.replace(/^returns?\s+/, '')
      .trim(),
    examples: tags
      .filter((tag) => tag.startsWith('example'))
      .map((tag) => tag.slice(7).trim()),
    deprecated: tags
      .find((tag) => tag.startsWith('deprecated'))
      ?.slice(10)
      .trim(),
  }
}

export function parseDeclarations(input, source, group, names) {
  const ast = parse(source, {
    sourceType: 'module',
    plugins: ['typescript', 'jsx'],
  })
  const result = []
  for (const statement of ast.program.body) {
    const exported = statement.type === 'ExportNamedDeclaration'
    const declaration = exported ? statement.declaration : statement
    if (!declaration) continue
    const nodes =
      declaration.type === 'VariableDeclaration'
        ? declaration.declarations
        : [declaration]
    for (const node of nodes) {
      if (
        ![
          'TSTypeAliasDeclaration',
          'TSInterfaceDeclaration',
          'FunctionDeclaration',
          'VariableDeclarator',
        ].includes(node.type)
      )
        continue
      const name = node.id?.name
      if (!name || hidden.test(name)) continue
      result.push({
        name,
        node,
        input,
        source,
        group,
        exported: exported && (!names || names.includes(name)),
        docs: comment(statement.leadingComments ? statement : node),
      })
    }
  }
  return result
}

function text(record, node) {
  return node ? record.source.slice(node.start, node.end).trim() : ''
}
function compact(record, node) {
  return text(record, node)
    .replace(/\/\*[\s\S]*?\*\/|\/\/[^\n]*/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}
function annotation(node) {
  return node?.typeAnnotation?.typeAnnotation
}
function members(node, prefix = '', readonly = false) {
  if (!node) return []
  if (node.type === 'TSIntersectionType')
    return node.types.flatMap((type) => members(type, prefix, readonly))
  if (node.type === 'TSTypeReference' && node.typeName.name === 'Readonly')
    return members(node.typeParameters?.params[0], prefix, true)
  const items = node.members ?? node.body ?? []
  if (!Array.isArray(items)) return []
  return items.flatMap((member) => {
    const name = member.key?.name ?? member.key?.value
    if (!name) return []
    const path = prefix + name
    const nested =
      member.optional || member.readonly || readonly
        ? []
        : members(annotation(member), `${path}.`)
    if (nested.length) return nested
    return [
      {
        name: path,
        node: member,
        type: annotation(member),
        optional: member.optional,
        readonly: readonly || member.readonly,
        docs: comment(member),
      },
    ]
  })
}

function links(raw, names) {
  const content = raw.replace(
    /(?:'(?:[^'\\]|\\.)*'|"(?:[^"\\]|\\.)*"|\x60(?:[^\x60\\]|\\.)*\x60)|[A-Za-z_$][\w$]*|[^A-Za-z_$'"\x60]+|./gs,
    (token) =>
      names.has(token)
        ? `<a href="${token}.md">${token}</a>`
        : escapeHtml(token),
  )
  return `<code>${content}</code>`
}
function related(record, node, names) {
  const signature =
    node?.type === 'FunctionDeclaration'
      ? functionSignature(record)
      : text(record, node)
  const refs = [
    ...new Set(signature.match(/\b[A-Za-z_$][\w$]*\b/g) ?? []),
  ].filter((name) => names.has(name) && name !== record.name)
  return refs.length
    ? `Related: ${refs.map((name) => `[${name}](${name}.md)`).join(', ')}.`
    : ''
}
function sourceLink(record, node = record.node) {
  return (
    '[Source](https://github.com/schmayterling/hibi/blob/main/' +
    record.input +
    '#L' +
    node.loc.start.line +
    ')'
  )
}
function parameters(record, callable, docs, names) {
  const params = callable.parameters ?? callable.params ?? []
  const descriptions = docs.parameters.size > 0
  const rows = params.map((param, index) => {
    const value = param.type === 'AssignmentPattern' ? param.left : param
    const name =
      value.name ??
      (value.type === 'RestElement'
        ? `...${value.argument.name}`
        : index === 0
          ? 'props'
          : `argument${index + 1}`)
    return (
      '| ' +
      links(name + (value.optional ? '?' : ''), new Map()) +
      ' | ' +
      links(compact(record, annotation(value)) || 'unknown', names) +
      (descriptions
        ? ` | ${escapeHtml(docs.parameters.get(name) ?? '')}`
        : '') +
      ' |'
    )
  })
  const result = []
  if (rows.length)
    result.push(
      (descriptions
        ? '**Parameters**\n\n| Name | Type | Description |\n| --- | --- | --- |\n'
        : '**Parameters**\n\n| Name | Type |\n| --- | --- |\n') +
        rows.join('\n'),
    )
  const returns =
    callable.typeAnnotation?.typeAnnotation ??
    callable.returnType?.typeAnnotation
  if (returns)
    result.push(
      '**Returns:** ' +
        links(compact(record, returns), names) +
        (docs.returns ? `\n\n${docs.returns}` : ''),
    )
  return result.join('\n\n')
}
function functionSignature(record) {
  const node = record.node
  const args = node.params
    .map((param, index) => {
      if (param.type === 'ObjectPattern')
        return (
          (index ? `argument${index + 1}` : 'props') +
          text(record, param.typeAnnotation)
        )
      return text(record, param)
    })
    .join(', ')
  return (
    'function ' +
    record.name +
    text(record, node.typeParameters) +
    '(' +
    args +
    ')' +
    text(record, node.returnType)
  )
}
function page(record, names) {
  const { node, docs, name } = record
  const entries = members(node.typeAnnotation ?? node.body)
  const isFunction = node.type === 'FunctionDeclaration'
  const kind = isFunction
    ? 'Function'
    : node.type === 'VariableDeclarator'
      ? 'Constant'
      : node.type === 'TSInterfaceDeclaration'
        ? 'Interface'
        : 'Type alias'
  const result = [
    generatedNotice,
    `# ${name}`,
    kind +
      (record.exported ? '' : ' · Supporting type') +
      ' · ' +
      sourceLink(record),
    docs.description,
  ]
  if (docs.deprecated !== undefined)
    result.push(`**Deprecated.** ${docs.deprecated}`)
  const signature = isFunction
    ? functionSignature(record)
    : node.type === 'VariableDeclarator'
      ? `const ${text(record, node)}`
      : text(record, node)
  if (entries.length)
    result.push(
      '<details>\n<summary>Declaration</summary>\n\n' +
        fence(signature) +
        '\n\n</details>',
    )
  else result.push(fence(signature))
  if (isFunction || node.typeAnnotation?.type === 'TSFunctionType')
    result.push(
      parameters(record, isFunction ? node : node.typeAnnotation, docs, names),
    )
  if (entries.length) {
    const method = (entry) =>
      entry.node.type === 'TSMethodSignature' ||
      entry.type?.type === 'TSFunctionType'
    const groups = [
      ['Properties', entries.filter((entry) => !method(entry))],
      ['Methods', entries.filter(method)],
    ]
    result.push(
      '## Contents',
      ...groups
        .filter(([, items]) => items.length)
        .map(
          ([title, items]) =>
            '**' +
            title +
            '**\n\n' +
            items
              .map((item) => `- [${item.name}](#${anchor(item.name)})`)
              .join('\n'),
        ),
    )
    for (const [title, items] of groups) {
      if (!items.length) continue
      result.push(`## ${title}`)
      for (const entry of items) {
        const flags = [
          entry.readonly && 'Readonly',
          entry.optional && 'Optional',
        ].filter(Boolean)
        const signature =
          (entry.readonly ? 'readonly ' : '') +
          entry.name.slice(
            0,
            entry.name.length -
              String(entry.node.key.name ?? entry.node.key.value).length,
          ) +
          text(record, entry.node.key) +
          (entry.optional && entry.node.type !== 'TSMethodSignature'
            ? '?'
            : '') +
          (entry.type && entry.node.type !== 'TSMethodSignature'
            ? `: ${text(record, entry.type)}`
            : record.source.slice(entry.node.key.end, entry.node.end))
        result.push(
          `### ${entry.name}`,
          [...flags, sourceLink(record, entry.node)].join(' · '),
          entry.docs.description,
          fence(signature),
          related(record, entry.type, names),
        )
        if (method(entry))
          result.push(
            parameters(
              record,
              entry.node.type === 'TSMethodSignature' ? entry.node : entry.type,
              entry.docs,
              names,
            ),
          )
      }
    }
  }
  const references = related(record, node, names)
  if (references)
    result.push('## Related types', references.replace(/^Related: /, ''))
  if (docs.examples.length)
    result.push(
      '## Examples',
      ...docs.examples.map((example) =>
        example.startsWith(ticks) ? example : fence(example),
      ),
    )
  return `${result.filter(Boolean).join('\n\n')}\n`
}

export function referencePages(records) {
  const all = new Map(records.map((record) => [record.name, record]))
  const selected = new Map(
    records
      .filter((record) => record.exported)
      .map((record) => [record.name, record]),
  )
  // Include helper types used by public signatures, never implementation bodies.
  for (const record of selected.values()) {
    const signature =
      record.node.type === 'FunctionDeclaration'
        ? functionSignature(record)
        : text(record, record.node)
    for (const name of signature.match(/\b[A-Za-z_$][\w$]*\b/g) ?? []) {
      const helper = all.get(name)
      if (
        helper &&
        /^TS(?:TypeAlias|Interface)Declaration$/.test(helper.node.type) &&
        !selected.has(name)
      )
        selected.set(name, helper)
    }
  }
  const sorted = [...selected.values()].sort((a, b) =>
    a.name.localeCompare(b.name, 'en'),
  )
  return new Map(
    sorted.map((record) => [
      `${referenceRoot}/${record.name}.md`,
      page(record, selected),
    ]),
  )
}

export async function generateReferences() {
  const records = (
    await Promise.all(
      referenceSources.map(async ([input, group, , names]) =>
        parseDeclarations(input, await readFile(input, 'utf8'), group, names),
      ),
    )
  ).flat()
  const outputs = referencePages(records)
  const groups = new Map()
  for (const [input, group, legacy] of referenceSources) {
    const entries = records.filter(
      (record) =>
        record.input === input &&
        outputs.has(`${referenceRoot}/${record.name}.md`),
    )
    if (!groups.has(group)) groups.set(group, [])
    groups.get(group).push(...entries)
    if (legacy) {
      const target = `docs/ai-agents/reference/${legacy}.md`
      const path = posix.relative(dirname(target), referenceRoot)
      outputs.set(
        target,
        generatedNotice +
          '\n\n# ' +
          group +
          '\n\nSee the [addon API reference](' +
          path +
          '/README.md).\n\n' +
          entries
            .map((entry) => `- [${entry.name}](${path}/${entry.name}.md)`)
            .join('\n') +
          '\n',
      )
    }
  }
  outputs.set(
    `${referenceRoot}/README.md`,
    generatedNotice +
      '\n\n# addon api reference\n\nLook up the types and functions available to addon authors. Start with [Addon](Addon.md), [AddonManifest](AddonManifest.md), and [AddonContext](AddonContext.md), or follow [Creating your first addon](../addons/creating-your-first-addon.md).\n\nFor installed packages, use the [SideloadFactory](SideloadFactory.md) and the [shared SDK](sdk.md). Native modules use [NativeAddon](NativeAddon.md) and [NativeAddonContext](NativeAddonContext.md).\n\n' +
      [...groups]
        .map(
          ([group, entries]) =>
            '## ' +
            group +
            '\n\n' +
            entries
              .sort((a, b) => a.name.localeCompare(b.name, 'en'))
              .map((entry) => `- [${entry.name}](${entry.name}.md)`)
              .join('\n'),
        )
        .join('\n\n') +
      '\n\n## Styling\n\n- [Theme tokens](theme-tokens.md)\n',
  )
  outputs.set(
    `${referenceRoot}/theme-tokens.md`,
    generatedNotice +
      '\n\n# Theme tokens\n\nUse these CSS variables for addon spacing, colors, and typography.\n\n' +
      ticks +
      'css\n' +
      (await readFile('src/ui/tokens.css', 'utf8')).trim() +
      '\n' +
      ticks +
      '\n',
  )
  outputs.set(
    'docs/ai-agents/reference/theme-tokens.md',
    generatedNotice +
      '\n\n# Theme tokens\n\nSee the [theme token reference](../../development/addon-api-reference/theme-tokens.md).\n',
  )
  return outputs
}

